#!/usr/bin/env python3
"""Backfill per-piece MIDI files for batches generated before MIDI retention.

The browse site plays code-gen pieces from their MIDI (html-midi-player), so
every published piece needs a .mid alongside its score. Batches generated by
this repo's pipeline store MIDI natively; batches imported from earlier runs
only carry MusicXML/ABC, and this script derives the MIDI the same way the
pipeline did:

- code-gen pieces: parse the stored MusicXML with music21 and write MIDI —
  exactly the conversion the generation sandbox used, so the result matches
  the MIDI the piece's archived audio was rendered from.
- ABC pieces: convert the stored ABC with abc2midi (must be on PATH), the
  same tool the pipeline's audio baking used. (The viewer plays ABC through
  the abcjs synth, so this is only for completeness of the shipped data.)

Updates each batch's data.json in place, adding a "midi" path per piece.
Idempotent: pieces whose MIDI file already exists are only re-linked.

Usage: .venv/bin/python scripts/bake_midi.py [--data-dir data] [--skip-abc]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from llm_music.render import abc_to_midi  # noqa: E402


def midi_rel_path(entry: dict) -> str:
    suffix = f"_s{entry['sample']}" if entry.get("sample") else ""
    return f"midi/{entry['prompt']}/{entry['model']}{suffix}.mid"


def bake_entry(batch: Path, entry: dict, skip_abc: bool) -> str:
    """Ensure entry has a MIDI file; return 'ok' | 'skipped' | an error string."""
    rel = midi_rel_path(entry)
    dst = batch / rel
    if dst.is_file():
        entry["midi"] = rel
        return "ok"
    if entry.get("abc"):
        if skip_abc:
            return "skipped"
        with tempfile.TemporaryDirectory(prefix="bake_midi_") as tmp:
            midi = abc_to_midi(entry["abc"], Path(tmp))
            if midi is None:
                return "abc2midi failed (is it installed?)"
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(midi, dst)
        entry["midi"] = rel
        return "ok"
    score = entry.get("score")
    if not score or not (batch / score).is_file():
        return "no stored score to derive MIDI from"
    from music21 import converter

    try:
        parsed = converter.parse(str(batch / score))
        dst.parent.mkdir(parents=True, exist_ok=True)
        parsed.write("midi", fp=str(dst))
    except Exception as exc:
        return f"music21 conversion failed: {exc}"
    entry["midi"] = rel
    return "ok"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir", default="data",
                    help="folder holding the batch subfolders (default: data)")
    ap.add_argument("--skip-abc", action="store_true",
                    help="only bake code-gen MIDI (ABC plays via the abcjs synth anyway)")
    args = ap.parse_args()
    base = Path(args.data_dir)
    batches = sorted(p for p in base.iterdir() if (p / "data.json").is_file())
    if not batches:
        print(f"no batches under {base}")
        return 1
    total_ok = total_err = 0
    for batch in batches:
        manifest_path = batch / "data.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        n_ok = n_err = 0
        for entry in manifest.get("pieces", []):
            if not entry.get("ok"):
                continue
            status = bake_entry(batch, entry, args.skip_abc)
            if status == "ok":
                n_ok += 1
            elif status != "skipped":
                n_err += 1
                print(f"  {batch.name}: {entry['model']} × {entry['prompt']}"
                      f" #{entry.get('sample', 0)}: {status}")
        manifest_path.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        total_ok += n_ok
        total_err += n_err
        print(f"{batch.name}: {n_ok} MIDI baked/linked"
              + (f", {n_err} failed" if n_err else ""))
    print(f"Done: {total_ok} pieces have MIDI"
          + (f", {total_err} failed" if total_err else ""))
    return 0 if not total_err else 1


if __name__ == "__main__":
    raise SystemExit(main())
